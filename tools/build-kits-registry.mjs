// tools/build-kits-registry.mjs — generate a STATIC kit registry for browser Chrome < 89 compatibility.
//
// server/sim/content/kits/index.js used to dynamic-import every ops/*.js at module top level (`await Promise.all`),
// which is top-level await — unsupported in Android WebView Chrome < 89 (test/es2020-syntax.test.js, blackscreen gate).
// This generator replaces that runtime scan with static imports: every kit file is read once at build time; a file
// that cannot be statically imported (syntax error, missing) is simply not listed — the consumer logs and skips it
// exactly like the old guarded loader, but without the TLA.
//
// Run:  node tools/build-kits-registry.mjs   (regenerates server/sim/content/kits/registry.js + its public/ mirror)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX = path.join(ROOT, 'server/sim/content/kits/index.js');
const OUT_SERVER = path.join(ROOT, 'server/sim/content/kits/registry.js');
const OUT_PUBLIC = path.join(ROOT, 'public/sim/content/kits/registry.js');

// Extract each file list from kits/index.js with a declaration-anchored regex (the KIT_FILES block ends with
// `.map((group) => Object.freeze(group)));`, not a plain `]);`, so match the full statement to its semicolon).
const idx = fs.readFileSync(INDEX, 'utf8');
const statementOf = (name) => {
  const re = new RegExp(`export const ${name} = Object\\.freeze\\(([\\s\\S]*?)\\);`);
  const m = idx.match(re);
  if (!m) throw new Error(`${name} not found in kits/index.js`);
  return m[1];
};
const stringsIn = (block) => [...block.matchAll(/'([^']+\.js)'/g)].map((x) => x[1]);

// KIT_FILES = [[tier1...], [tier2...], ...].map(...): split the top-level groups
const KIT_FILES = [];
{
  const body = statementOf('KIT_FILES').replace(/\.map\([^)]*\)\s*$/, '');
  const groupRe = /\[\s*([^\]]*?)\s*\](?=,|\n|$)/g;
  let g;
  while ((g = groupRe.exec(body))) {
    const files = stringsIn(g[1]);
    if (files.length) KIT_FILES.push(files);
  }
}
const STANDIN_KIT_FILES = stringsIn(statementOf('STANDIN_KIT_FILES'));
const OPERATOR_KIT_FILES = stringsIn(statementOf('OPERATOR_KIT_FILES'));

if (KIT_FILES.length !== 6) { console.error(`expected 6 tier groups, parsed ${KIT_FILES.length}`); process.exit(1); }

// every referenced file must exist (a missing file was a silent skip in the runtime loader; here it fails the build)
const missing = [];
for (const f of [...KIT_FILES.flat(), ...STANDIN_KIT_FILES, ...OPERATOR_KIT_FILES]) {
  if (!fs.existsSync(path.join(ROOT, 'server/sim/content/kits/ops', f))) missing.push(f);
}
if (missing.length) { console.error('missing kit files:', missing.join(', ')); process.exit(1); }

// static-import each file once (`import kitN from './ops/x.js'` binds the default export — the kit registry object
// itself, NOT the module namespace — so a file with `export default {…}` contributes its keys directly).
const flat = [];
KIT_FILES.forEach((group, gi) => group.forEach((f) => flat.push({ f, gi, kind: 'tier' })));
STANDIN_KIT_FILES.forEach((f) => flat.push({ f, kind: 'standin' }));
OPERATOR_KIT_FILES.forEach((f) => flat.push({ f, kind: 'op' }));

const reg = (v) => `(${v} && typeof ${v} === 'object' ? ${v} : {})`;

let seq = 0;
const imports = flat.map(({ f }) => `import kit${seq++} from './ops/${f}';`);

const lines = [];
lines.push(...imports);
lines.push('');
// TIER_KITS: one merged object per group, in file order (a later file in the same group shadows an earlier key)
seq = 0;
const tierObjs = KIT_FILES.map((group) => {
  const mods = group.map(() => `kit${seq++}`);
  return `Object.assign({}, ...[${mods.join(', ')}].map((m) => ${reg('m')}))`;
});
lines.push(`export const TIER_KITS = Object.freeze([${tierObjs.map((o) => `\n  ${o}`).join(',')},\n]);`);
const standinObjs = flat.filter((x) => x.kind === 'standin').map(() => `kit${seq++}`).map((m) => reg(m));
lines.push(`export const STANDIN_KITS = Object.freeze(Object.assign({}, ${standinObjs.join(', ')}));`);
const opObjs = flat.filter((x) => x.kind === 'op').map(() => `kit${seq++}`).map((m) => reg(m));
lines.push(`export const OPERATOR_KITS = Object.freeze(Object.assign({}, ${opObjs.join(', ')}));`);
lines.push('');
lines.push('export const KITS = Object.freeze(Object.assign({}, ...TIER_KITS, STANDIN_KITS, OPERATOR_KITS));');
lines.push('');

const out = `// GENERATED FILE — regenerated by tools/build-kits-registry.mjs; edit kits/ops/*, never this file.
// Static kit registry (no top-level await): the runtime dynamic-import loader in kits/index.js required Chrome 89+;
// Android WebViews of older builds black-screened on it (test/es2020-syntax.test.js gate). Build-time generation keeps
// the same key order and the same graceful per-file default-export handling, with zero runtime cost.
${lines.join('\n')}`;

for (const target of [OUT_SERVER, OUT_PUBLIC]) {
  fs.writeFileSync(target, out);
  console.log('wrote', path.relative(ROOT, target), `(${flat.length} kit files: ${KIT_FILES.length} tiers + ${STANDIN_KIT_FILES.length} stand-ins + ${OPERATOR_KIT_FILES.length} operators)`);
}
