import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_DIR = path.join(ROOT, 'public');

function copyRecursive(src, dest, filterFn = null) {
  if (!fs.existsSync(src)) return;
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    fs.mkdirSync(dest, { recursive: true });
    for (const file of fs.readdirSync(src)) {
      copyRecursive(path.join(src, file), path.join(dest, file), filterFn);
    }
  } else {
    if (filterFn && !filterFn(src)) return;
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(src, dest);
  }
}

export function syncStaticWeb() {
  console.log('[sync-static-web] Syncing standalone web assets into public/...');

  // 1. shared/ -> public/shared/
  copyRecursive(path.join(ROOT, 'shared'), path.join(PUBLIC_DIR, 'shared'));

  // 2. data/ -> public/data/
  copyRecursive(path.join(ROOT, 'data'), path.join(PUBLIC_DIR, 'data'));

  // 3. server/sim/ -> public/sim/ (.js only, exclude nodedata.js)
  const simSrc = path.join(ROOT, 'server', 'sim');
  const simDst = path.join(PUBLIC_DIR, 'sim');
  fs.mkdirSync(simDst, { recursive: true });

  copyRecursive(simSrc, simDst, (filePath) => {
    const ext = path.extname(filePath).toLowerCase();
    const base = path.basename(filePath).toLowerCase();
    return ext === '.js' && base !== 'nodedata.js';
  });

  // Patch simdata.js to strip Node-only IS_NODE block
  const simDataFile = path.join(simDst, 'simdata.js');
  if (fs.existsSync(simDataFile)) {
    const raw = fs.readFileSync(simDataFile, 'utf8');
    const patched = raw.replace(
      /if\s*\(\s*IS_NODE\s*\)\s*\{[\s\S]*?\n\}/,
      '/* browser: nodeLoader omitted (setSimData injects data) */'
    );
    fs.writeFileSync(simDataFile, patched, 'utf8');
  }

  // 4. Generate public/data.js
  const dataJsContent = `// Generated by tools/sync-static-web.mjs — browser stand-in for server/data.js
import { getSimData } from './sim/simdata.js';
export function getData() { return getSimData() || {}; }
export function resetData() {}
`;
  fs.writeFileSync(path.join(PUBLIC_DIR, 'data.js'), dataJsContent, 'utf8');

  console.log('[sync-static-web] Sync complete: public/ is now fully self-contained!');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  syncStaticWeb();
}
